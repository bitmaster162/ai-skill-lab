#!/usr/bin/env python3
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]; checks=0; errors=[]
surfaces=[(ROOT/'app/proof/page.tsx',False,'source RU'),(ROOT/'app/en/proof/page.tsx',True,'source EN'),(ROOT/'deploy/live/proof.html',False,'static RU'),(ROOT/'deploy/live/en/proof.html',True,'static EN')]
for path,en,label in surfaces:
 checks+=1
 if not path.exists(): errors.append(f'{label}: missing'); continue
 text=path.read_text(encoding='utf-8')
 for m in ['SITE AS PROOF','DEFINE','BUILD','VERIFY','SHIP','HASHED CSP','BYTE-EXACT','Release manifest']:
  checks+=1
  if m not in text: errors.append(f'{label}: missing {m}')
 marks=['not a hidden AI call','not a data-collection form','What this site does','not</em> prove'] if en else ['не скрытый AI-вызов','не сбор персональных данных','Что этот сайт','не</em> доказывает']
 for m in marks:
  checks+=1
  if m not in text: errors.append(f'{label}: missing honesty {m}')
 for bad in ['live AI model','real-time AI model','powered by GPT','generated by ChatGPT']:
  checks+=1
  if bad.lower() in text.lower(): errors.append(f'{label}: forbidden {bad}')
for rel in ['app/page.tsx','app/en/page.tsx','deploy/live/index.html','deploy/live/en.html']:
 text=(ROOT/rel).read_text(encoding='utf-8'); checks+=2
 if 'Site as proof' not in text: errors.append(f'{rel}: missing Site as proof')
 if '/proof' not in text: errors.append(f'{rel}: missing proof link')
if errors:
 print(f'proof_route_checks={checks}'); [print('FAIL:',e) for e in errors]; sys.exit(1)
print(f'proof_route_checks={checks} surfaces=4'); print('PROOF_ROUTE_PARITY_PASS')
